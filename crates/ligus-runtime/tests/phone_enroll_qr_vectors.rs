/// splitmix64: a fixed, portable stream for the mutations.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

/// Text-level spellings every format must refuse (or, for the last
/// character, may read as another value).
fn text_mutations(text: &str, prefix: &str) -> Vec<String> {
    let body = text.strip_prefix(prefix).unwrap();
    let mut out = vec![
        body.to_string(),
        format!("{}{body}", prefix.to_uppercase()),
        format!("{}{body}", prefix.trim_end_matches(':')),
        format!(
            "{}2:{body}",
            prefix.trim_end_matches(|c: char| c == ':' || c.is_ascii_digit())
        ),
        format!(" {text}"),
        format!("{text} "),
        format!("{text}\n"),
        format!("{text}="),
        format!("{text}=="),
        format!("{prefix} {body}"),
        format!(
            "{prefix}{}\n{}",
            &body[..body.len() / 2],
            &body[body.len() / 2..]
        ),
        text.replacen('-', "+", 1),
        text.replacen('_', "/", 1),
        format!("{text}A"),
        format!("{text}AA"),
        format!("{text}AAA"),
        format!("{text}AAAA"),
        text[..text.len() - 1].to_string(),
        text[..text.len() - 2].to_string(),
        text[..text.len() - 3].to_string(),
        text[..text.len() - 4].to_string(),
        prefix.to_string(),
        String::new(),
    ];
    // Every replacement of the last character (trailing bits, or a value).
    let alphabet = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
    for c in [alphabet[1], alphabet[2], alphabet[17], alphabet[63], b'='] {
        let mut s = text[..text.len() - 1].to_string();
        s.push(c as char);
        out.push(s);
    }
    out.retain(|s| s != text);
    out
}

/// Byte-level mutations, canonically re-encoded.
fn byte_mutations(text: &str, prefix: &str, rng: &mut Rng, n: usize) -> Vec<String> {
    let b = URL_SAFE_NO_PAD
        .decode(text.strip_prefix(prefix).unwrap())
        .unwrap();
    let mut out = Vec::new();
    for i in 0..n {
        let mut m = b.clone();
        match i % 5 {
            0 | 1 => {
                let bit = rng.below(m.len() * 8);
                m[bit / 8] ^= 1 << (bit % 8);
            }
            2 => {
                let at = rng.below(m.len());
                m[at] = rng.next() as u8;
            }
            3 => {
                let keep = rng.below(m.len());
                m.truncate(keep);
            }
            _ => {
                let extra = 1 + rng.below(8);
                m.extend((0..extra).map(|_| rng.next() as u8));
            }
        }
        if m != b {
            out.push(with_body(prefix, &m));
        }
    }
    out
}

fn generate_parity() -> String {
    let mut rng = Rng(0x6c69_6775_7365_6e72); // "liguseng"
    let mut out = Vec::new();
    let mut id = 0usize;
    let mut push = |pairs: Vec<(&str, Value)>| {
        let mut p = vec![("id", json!(id))];
        p.extend(pairs);
        out.push(line(p));
        id += 1;
    };
    let a = phone(0x21);
    let b = phone(0x22);
    let valid = offer(0x51, NOW + 300);
    let offer_text = valid.encode().to_string();

    // offers
    let mut offers = vec![offer_text.clone()];
    offers.extend(text_mutations(&offer_text, OFFER_PREFIX));
    offers.extend(byte_mutations(&offer_text, OFFER_PREFIX, &mut rng, 40));
    for t in &offers {
        push(vec![
            ("mode", json!("offer")),
            ("text", json!(t)),
            ("nowMs", json!(NOW_MS)),
            ("rust", json!(offer_verdict(t, NOW_MS))),
        ]);
    }
    // Clock edges: exp − now (s) on the phone.
    for delta in [
        -181i64, -121, -120, -119, -60, 0, 299, 300, 599, 600, 601, 3600,
    ] {
        let t = offer(0x51, (NOW as i64 + delta) as u64)
            .encode()
            .to_string();
        push(vec![
            ("mode", json!("offer")),
            ("text", json!(t)),
            ("nowMs", json!(NOW_MS)),
            ("rust", json!(offer_verdict(&t, NOW_MS))),
        ]);
    }
    for (ms, exp) in [
        (NOW_MS - 1, NOW - 120),
        (NOW_MS + 1, NOW - 120),
        (NOW_MS + 999, NOW - 120),
        (NOW_MS - 1, NOW + 600),
        (NOW_MS + 1, NOW + 600),
    ] {
        let t = offer(0x51, exp).encode().to_string();
        push(vec![
            ("mode", json!("offer")),
            ("text", json!(t)),
            ("nowMs", json!(ms)),
            ("rust", json!(offer_verdict(&t, ms))),
        ]);
    }
    for exp in [0u64, u64::MAX, i64::MAX as u64 + 1] {
        let t = offer(0x51, exp).encode().to_string();
        push(vec![
            ("mode", json!("offer")),
            ("text", json!(t)),
            ("nowMs", json!(NOW_MS)),
            ("rust", json!(offer_verdict(&t, NOW_MS))),
        ]);
    }

    // requests
    let req = |label: &str, p: &TestPhone| {
        EnrollRequest::build(&valid, &p.code(label), |m| p.sign(m)).encode()
    };
    let ra = req("Ana's iPhone", &a);
    let mut requests = vec![ra.clone(), req("", &a), req(&"é".repeat(32), &b)];
    requests.extend(text_mutations(&ra, REQUEST_PREFIX));
    requests.extend(byte_mutations(&ra, REQUEST_PREFIX, &mut rng, 90));
    let req_case = |t: &str, now_ms: i64| {
        vec![
            ("mode", json!("request")),
            ("offer", json!(offer_text)),
            ("text", json!(t)),
            ("nowMs", json!(now_ms)),
            ("boxWorkspaceId", json!(valid.workspace_id)),
            ("rust", json!(desktop_verdict(&offer_text, t, now_ms))),
            (
                "rustBox",
                json!(box_verdict(t, valid.workspace_id, None, now_ms)),
            ),
        ]
    };
    for t in &requests {
        push(req_case(t, NOW_MS));
    }
    let end = (NOW + 300) as i64 * 1000;
    for ms in [
        end,
        end + 1,
        end + 120_000,
        end + 120_001,
        NOW_MS - 120_000,
        NOW_MS - 120_001,
    ] {
        push(req_case(&ra, ms));
    }

    // answers
    let d = DesktopOffer::from_offer(valid.clone());
    let good = d.answer(Outcome::Certified, a.device_id).encode();
    let mut answers = vec![
        good.clone(),
        d.answer(Outcome::Declined, a.device_id).encode(),
        d.answer(Outcome::Refused, a.device_id).encode(),
        d.answer(Outcome::Certified, b.device_id).encode(),
        d.answer(Outcome::Declined, b.device_id).encode(),
    ];
    answers.extend(text_mutations(&good, ANSWER_PREFIX));
    answers.extend(byte_mutations(&good, ANSWER_PREFIX, &mut rng, 50));
    let gb = body(&good, ANSWER_PREFIX);
    for o in [0u8, 1, 2, 3, 4, 0x81, 0xff] {
        let mut m = gb.clone();
        m[16] = o;
        answers.push(with_body(ANSWER_PREFIX, &m));
    }
    answers.push(
        DesktopOffer::from_offer(offer(0x52, NOW + 300))
            .answer(Outcome::Certified, a.device_id)
            .encode(),
    );
    for t in &answers {
        push(vec![
            ("mode", json!("answer")),
            ("offer", json!(offer_text)),
            ("text", json!(t)),
            ("phoneDeviceId", json!(a.device_id)),
            ("rust", json!(answer_verdict(&offer_text, t, a.device_id))),
        ]);
    }

    // Requests made with the offer's secret (the MAC passes) that a later
    // check decides: labels the desktop's clamp keeps but a stricter
    // phone-side clamp would drop (the phone's verifier must follow the
    // desktop's rule), a high S, a label that isn't its own clamp, and
    // another workspace under the same secret. Appended, so earlier ids stay.
    let mut late = Vec::new();
    for label in [
        "Ana\u{2028}iPhone",
        "Ana\u{2029}",
        "Ana\u{E0041}\u{E007F}",
        "\u{0600}Ana",
        "Ana\u{110BD}",
        "Ana\u{FFFC}",
        "Ana \u{1F1EB}\u{1F1F7}",
        "Ana\u{0301}",
    ] {
        late.push(req(label, &a));
    }
    late.push(EnrollRequest::build(&valid, &a.code("Ana's iPhone"), |m| high_s(&a.sign(m))).encode());
    let unclamped = {
        let label = " Ana".to_string();
        let pre = ligus_runtime::phone_enroll::preimage(a.device_id, &a.public_key, &label);
        PhoneCode { device_id: a.device_id, public_key: a.public_key.clone(), label, signature: a.sign(&pre) }
    };
    late.push(EnrollRequest::build(&valid, &unclamped, |m| a.sign(m)).encode());
    let elsewhere = Offer { workspace_id: u(9), ..valid.clone() };
    late.push(EnrollRequest::build(&elsewhere, &a.code("Ana's iPhone"), |m| a.sign(m)).encode());
    for t in &late {
        push(req_case(t, NOW_MS));
    }

    let mut s = out.join("\n");
    s.push('\n');
    s
}

