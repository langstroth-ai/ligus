//! Golden vectors and the iOS differential corpus for reverse-QR phone
//! enrollment (`ligus_runtime::phone_enroll_qr`,
//! `docs/design/v2/phone-enroll-reverse-qr.md` §5).
//!
//! `crates/ligus-core/tests/golden/phone_enroll_qr_v1.jsonl`: one line per
//! case, with `label`, `check` and the inputs, and `expect`: `"ok"` or the
//! exact refusal (`EnrollError::code`; for the box, `BoxRefusal::error`, and
//! `bad_request/<code>` when the request didn't decode). Accepted cases also
//! carry every intermediate value (`rid`, `kReq`, `kAns`, `signed`,
//! `phoneSig`, `mac`, `tag`, the slot preimages and signatures), so a port
//! can check each step. Fixed secrets, ids and keys; the P-256 signatures
//! are RFC 6979 (deterministic), the Ed25519 ones deterministic too.
//! - `keys`: `secret` (hex) → `rid`, `kReq`, `kAns` (hex), `ridB64u`.
//! - `offer`: `offer` and `nowMs` → `PhoneOffer::scan`; accepted cases also
//!   carry `workspaceId`, `desktopDeviceId`, `secret`, `exp`, `rid`.
//! - `request`: the desktop's `offer`, the `request`, `nowMs`,
//!   `boxWorkspaceId`, `callerDeviceId` (or null) → `expectBox`
//!   (`box_check_request`) and `expectDesktop` (`DesktopOffer::check_request`).
//! - `answer`: the `offer`, `answer`, `phoneDeviceId` →
//!   `PhoneOffer::check_answer`: `ok mine <outcome>`, `ok another <outcome>`.
//! - `requestSlot` / `answerSlot`: the slot's JSON (`relayed`), its name,
//!   `nowMs`, the signer's Ed25519 `slotKey` (hex) → `check_relayed_request`
//!   / `check_relayed_answer`, with the `preimage` they sign.
//!
//! `crates/ligus-core/tests/golden/differential/rust_parity_enroll_v1.jsonl`:
//! the iOS app's differential corpus (as `rust_parity_v1.jsonl` for phone
//! actions): seeded mutations of valid offers, requests and answers (bit
//! flips, truncations, extensions, prefix spellings, padding, `+` and `/`,
//! trailing bits, clock edges, outcome bytes), each with the core's answer in
//! `rust` (and `rustBox` for requests). The phone must give the same answer.
//!
//! Both files are generated by this file (deterministically) and checked
//! against a fresh generation on every run. To change them (only when
//! adding cases; a changed existing line is a wire break), run
//! `LIGUS_GOLDEN_OUT=<dir> cargo test -p ligus-runtime --test
//! phone_enroll_qr_vectors -- --ignored`, then copy both files in (and into
//! the iOS app's `LigusTests/Fixtures/golden/` and `differential/`).

