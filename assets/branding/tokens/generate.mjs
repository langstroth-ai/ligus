#!/usr/bin/env node
// Generates every colour file from ../ligus-brand-tokens.json:
//
//   web/src/lib/tokens.generated.ts        palettes and scheme tokens for theme.ts
//   web/src/tokens.generated.css           first-paint :root defaults (OKLCH with rgb() fallback)
//   assets/branding/generated/ios/LigusTokens.xcassets   colour catalogue for the phone
//   assets/branding/generated/ios/LigusTokens.generated.swift  the same values as RGBA literals
//   assets/branding/generated/lt/ligus_tokens.rs          lt's colour table (truecolor, 256, 16)
//
//   node assets/branding/tokens/generate.mjs           write the files
//   node assets/branding/tokens/generate.mjs --check   exit 1 if any file is stale
//
// The rgb() values are the OKLCH colours rounded to 8-bit sRGB, so every
// surface paints exactly the same channels.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { nearestXterm, over, parse, rgbOf, toRgbCss } from "./color.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const REPO = path.resolve(here, "..", "..", "..");
export const TOKENS_PATH = path.join(here, "..", "ligus-brand-tokens.json");

const HEADER = "GENERATED by assets/branding/tokens/generate.mjs from assets/branding/ligus-brand-tokens.json. Do not edit; edit the JSON and rerun the generator.";
const PALETTE_KEYS = ["canvas", "ink", "panel", "mist", "line", "accentWarm", "accentCool", "sidebarTop", "sidebarBottom", "sidebarInk", "sidebarInkMuted"];
const STATUS_KEYS = ["ok", "info", "warn", "danger", "neutral"];
const DIFF_KEYS = ["addBg", "addInk", "delBg", "delInk", "comment"];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
// The desktop's CSS names for the status roles (`ok` shipped as --ligus-success).
const STATUS_CSS = { ok: "success", info: "info", warn: "warn", danger: "danger", neutral: "neutral" };

/** Every generated file, as { relativePath: contents }. */
export function render(tokens) {
  const files = {};
  files["web/src/lib/tokens.generated.ts"] = renderTs(tokens);
  files["web/src/tokens.generated.css"] = renderCss(tokens);
  Object.assign(files, renderXcassets(tokens));
  files["assets/branding/generated/ios/LigusTokens.generated.swift"] = renderSwift(tokens);
  files["assets/branding/generated/lt/ligus_tokens.rs"] = renderRust(tokens);
  return files;
}

// ---- desktop ---------------------------------------------------------------

function schemeValues(s) {
  const out = {};
  for (const k of STATUS_KEYS) out[STATUS_CSS[k]] = toRgbCss(s.status[k]);
  out.overlay = toRgbCss(s.overlay);
  out.onAccent = toRgbCss(s.onAccent);
  Object.assign(out, s.numbers);
  for (const k of DIFF_KEYS) out[`diff${k[0].toUpperCase()}${k.slice(1)}`] = toRgbCss(s.diff[k]);
  return out;
}

function renderTs(t) {
  const palettes = {};
  for (const [name, fam] of Object.entries(t.themes)) {
    palettes[name] = {};
    for (const [variant, p] of Object.entries(fam)) {
      palettes[name][variant] = Object.fromEntries([...PALETTE_KEYS.map((k) => [k, toRgbCss(p[k])]), ["scheme", p.scheme]]);
    }
  }
  const schemes = {};
  for (const [name, s] of Object.entries(t.schemes)) schemes[name] = { ...schemeValues(s), presence: s.presence.map(toRgbCss) };
  return `// ${HEADER}

/** The palette families, light and dark, as rgb() strings (theme.ts applies them). */
export const PALETTES = ${JSON.stringify(palettes, null, 2)} as const;

/** Tokens that depend only on light or dark, never on the palette family. */
export const SCHEME_TOKENS = ${JSON.stringify(schemes, null, 2)} as const;

/** One glyph per state on every surface; colour is never the only cue. */
export const STATE_GLYPHS = ${JSON.stringify(t.states, null, 2)} as const;

export const MOTION = ${JSON.stringify(t.motion, null, 2)} as const;
`;
}

function renderCss(t) {
  const p = t.themes.pollen.light;
  const s = t.schemes.light;
  const pairs = [];
  for (const k of PALETTE_KEYS) pairs.push([`--ligus-${kebab(k)}`, p[k]]);
  for (const k of STATUS_KEYS) pairs.push([`--ligus-${STATUS_CSS[k]}`, s.status[k]]);
  pairs.push(["--ligus-overlay", s.overlay], ["--ligus-on-accent", s.onAccent]);
  for (const k of DIFF_KEYS) pairs.push([`--ligus-diff-${kebab(k)}`, s.diff[k]]);
  s.presence.forEach((c, i) => pairs.push([`--ligus-presence-${i + 1}`, c]));
  const rgbLines = pairs.map(([n, c]) => `  ${n}: ${toRgbCss(c)};`).join("\n");
  const oklchLines = pairs.map(([n, c]) => `    ${n}: ${c};`).join("\n");
  const numbers = Object.entries(s.numbers).map(([k, v]) => `  --ligus-${kebab(k)}: ${v};`).join("\n");
  const MOTION_CSS = { dur: "--ligus-dur", durSlow: "--ligus-dur-slow", pulse: "--ligus-dur-pulse" };
  const motion = Object.entries(t.motion).map(([k, v]) => `  ${MOTION_CSS[k]}: ${v};`).join("\n");
  return `/* ${HEADER}
   First-paint defaults: Pollen, light. applyTheme() (lib/theme.ts) sets the
   chosen palette and scheme on :root at runtime. */
:root {
${rgbLines}
${numbers}
${motion}
}
@supports (color: oklch(0 0 0)) {
  :root {
${oklchLines}
  }
}
`;
}

// ---- phone -----------------------------------------------------------------

const hex2 = (v) => "0x" + v.toString(16).toUpperCase().padStart(2, "0");
function colorComponents(css) {
  const c = parse(css);
  const [r, g, b] = rgbOf(c);
  return { "color-space": "srgb", components: { red: hex2(r), green: hex2(g), blue: hex2(b), alpha: Number(c.a.toFixed(3)).toString() } };
}
const INFO = { author: "xcode", version: 1 };
const json = (o) => JSON.stringify(o, null, 2) + "\n";

function colorset(light, dark) {
  const colors = [{ idiom: "universal", color: colorComponents(light) }];
  if (dark) colors.push({ idiom: "universal", appearances: [{ appearance: "luminosity", value: "dark" }], color: colorComponents(dark) });
  return json({ colors, info: INFO });
}

function renderXcassets(t) {
  const root = "assets/branding/generated/ios/LigusTokens.xcassets";
  const files = { [`${root}/Contents.json`]: json({ info: INFO }) };
  const group = (dir) => {
    files[`${root}/${dir}/Contents.json`] = json({ info: INFO, properties: { "provides-namespace": true } });
  };
  for (const [name, fam] of Object.entries(t.themes)) {
    group(name);
    for (const k of PALETTE_KEYS) files[`${root}/${name}/${k}.colorset/Contents.json`] = colorset(fam.light[k], fam.dark[k]);
  }
  const L = t.schemes.light;
  const D = t.schemes.dark;
  group("status");
  for (const k of STATUS_KEYS) files[`${root}/status/${k}.colorset/Contents.json`] = colorset(L.status[k], D.status[k]);
  group("diff");
  for (const k of DIFF_KEYS) files[`${root}/diff/${k}.colorset/Contents.json`] = colorset(L.diff[k], D.diff[k]);
  group("presence");
  L.presence.forEach((c, i) => {
    files[`${root}/presence/presence${i + 1}.colorset/Contents.json`] = colorset(c, D.presence[i]);
  });
  return files;
}

function swiftRgba(css) {
  const c = parse(css);
  const [r, g, b] = rgbOf(c);
  return c.a >= 1 ? `RGBA(${r}, ${g}, ${b})` : `RGBA(${r}, ${g}, ${b}, ${Number(c.a.toFixed(3))})`;
}

function renderSwift(t) {
  const fam = Object.entries(t.themes)
    .map(([name, f]) => {
      const pal = (p) => `Palette(${PALETTE_KEYS.map((k) => `${k}: ${swiftRgba(p[k])}`).join(", ")}, scheme: .${p.scheme})`;
      return `        .${name}: (light: ${pal(f.light)},\n                   dark: ${pal(f.dark)}),`;
    })
    .join("\n");
  const scheme = (s) =>
    `SchemeValues(${STATUS_KEYS.map((k) => `${k}: ${swiftRgba(s.status[k])}`).join(", ")}, overlay: ${swiftRgba(s.overlay)}, onAccent: ${swiftRgba(s.onAccent)}, ` +
    `${DIFF_KEYS.map((k) => `diff${k[0].toUpperCase()}${k.slice(1)}: ${swiftRgba(s.diff[k])}`).join(", ")}, presence: [${s.presence.map(swiftRgba).join(", ")}])`;
  const states = Object.entries(t.states)
    .map(([k, v]) => `        "${k}": StateGlyph(role: "${v.role}", word: "${v.word}", sfSymbol: "${v.sfSymbol}"),`)
    .join("\n");
  return `// ${HEADER}
//
// Drop-in values for the phone's Theme.swift types (RGBA, Palette, PaletteName).

enum LigusTokens {
    /// Every palette family, light and dark.
    static let families: [PaletteName: (light: Palette, dark: Palette)] = [
${fam}
    ]

    struct SchemeValues: Hashable, Sendable {
        let ok: RGBA, info: RGBA, warn: RGBA, danger: RGBA, neutral: RGBA
        let overlay: RGBA, onAccent: RGBA
        let diffAddBg: RGBA, diffAddInk: RGBA, diffDelBg: RGBA, diffDelInk: RGBA, diffComment: RGBA
        let presence: [RGBA]
    }

    /// Tokens that depend only on light or dark.
    static let light = ${scheme(t.schemes.light)}
    static let dark = ${scheme(t.schemes.dark)}

    struct StateGlyph: Hashable, Sendable {
        let role: String, word: String, sfSymbol: String
    }

    /// One SF Symbol per state; colour is never the only cue.
    static let states: [String: StateGlyph] = [
${states}
    ]
}
`;
}

// ---- lt --------------------------------------------------------------------

// 16-colour slots: the user's own palette, so ok stays green and so on. The
// accent and focus have no slot (None): yellow belongs to warn, so they use
// bold and reverse instead.
const ANSI = { ok: 2, danger: 1, warn: 3, info: 6, neutral: 8, diffAdd: 2, diffDel: 1, comment: 5 };

function renderRust(t) {
  const scheme = (variant) => {
    const p = t.themes.pollen[variant];
    const s = t.schemes[p.scheme];
    const bg = parse(p.canvas);
    const inkL = Number(s.numbers.accentInkL.replace("%", "")) / 100;
    const solid = (css) => rgbOf(parse(css)).map(Math.round);
    const atL = (css) => {
      // The status ink: the role's chroma and hue at the scheme's text lightness.
      const m = css.match(/oklch\(([\d.]+) ([\d.]+) ([\d.]+)/);
      return rgbOf(parse(`oklch(${inkL} ${m[2]} ${m[3]})`));
    };
    const mixed = (css, alpha) => over({ ...parse(css), a: alpha }, bg).map(Math.round);
    const tc = (rgb, ansi) => `TokenColor { rgb: (${rgb.join(", ")}), xterm256: ${nearestXterm(rgb)}, ansi16: ${ansi === undefined ? "None" : `Some(${ansi})`} }`;
    const rows = [
      ["text", tc(solid(p.ink))],
      ["dim", tc(mixed(p.ink, 0.7), 8)],
      ["accent", tc(solid(p.accentCool))],
      ["border", tc(over(parse(p.line), bg).map(Math.round), 8)],
      ["selection", tc(mixed(p.accentCool, 0.22))],
      ["mention", tc(solid(p.accentWarm))],
      ...STATUS_KEYS.map((k) => [k, tc(atL(s.status[k]), ANSI[k])]),
      ["diff_add", tc(solid(s.diff.addInk), ANSI.diffAdd)],
      ["diff_del", tc(solid(s.diff.delInk), ANSI.diffDel)],
      ["diff_comment", tc(solid(s.diff.comment), ANSI.comment)],
    ];
    const presence = s.presence.map((c) => `        ${tc(solid(c))},`).join("\n");
    return `SchemeTokens {\n${rows.map(([k, v]) => `    ${k}: ${v},`).join("\n")}\n    presence: [\n${presence}\n    ],\n}`;
  };
  const glyphs = Object.entries(t.states)
    .map(([k, v]) => `    StateGlyph { state: "${k}", role: "${v.role}", word: "${v.word}", glyph: "${v.lt}", ascii: "${v.ascii}" },`)
    .join("\n");
  return `//! ${HEADER}
//!
//! lt's colours from the shared Ligus tokens (the Pollen palette). Each colour
//! comes at three depths: truecolor RGB, the nearest xterm-256 index (16..255,
//! never the user-configurable 0..15) and a 16-colour ANSI slot. \`ansi16: None\`
//! means "no hue at 16 colours": use bold or reverse (the accent, since yellow
//! is reserved for warnings). Status colours are the text-weight inks.

/// One colour at three terminal depths.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TokenColor {
    pub rgb: (u8, u8, u8),
    pub xterm256: u8,
    pub ansi16: Option<u8>,
}

/// Every colour lt draws with, for one background.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SchemeTokens {
    pub text: TokenColor,
    pub dim: TokenColor,
    pub accent: TokenColor,
    pub border: TokenColor,
    pub selection: TokenColor,
    pub mention: TokenColor,
    pub ok: TokenColor,
    pub info: TokenColor,
    pub warn: TokenColor,
    pub danger: TokenColor,
    pub neutral: TokenColor,
    pub diff_add: TokenColor,
    pub diff_del: TokenColor,
    pub diff_comment: TokenColor,
    pub presence: [TokenColor; 8],
}

/// A state's glyph, with its \`--ascii\` form; the glyph is the invariant.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StateGlyph {
    pub state: &'static str,
    pub role: &'static str,
    pub word: &'static str,
    pub glyph: &'static str,
    pub ascii: &'static str,
}

pub const DARK: SchemeTokens = ${scheme("dark")};

pub const LIGHT: SchemeTokens = ${scheme("light")};

pub const STATE_GLYPHS: [StateGlyph; ${Object.keys(t.states).length}] = [
${glyphs}
];
`;
}

// ---- main ------------------------------------------------------------------

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((e) => e.isFile())
    .map((e) => path.join(e.parentPath ?? e.path, e.name));
}

/** The committed contents of a repo-relative file (for the parity tests). */
export function readRepoFile(rel) {
  return readFileSync(path.join(REPO, rel), "utf8");
}

/** Paths (relative to the repo) that differ from what the JSON generates. */
export function stale(tokens) {
  const files = render(tokens);
  const out = [];
  for (const [rel, body] of Object.entries(files)) {
    const abs = path.join(REPO, rel);
    if (!existsSync(abs) || readFileSync(abs, "utf8") !== body) out.push(rel);
  }
  // A generated file the JSON no longer produces is stale too.
  for (const abs of listFiles(path.join(REPO, "assets/branding/generated"))) {
    const rel = path.relative(REPO, abs).split(path.sep).join("/");
    if (!(rel in files) && !rel.endsWith("README.md")) out.push(rel);
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const tokens = JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
  if (process.argv.includes("--check")) {
    const bad = stale(tokens);
    for (const f of bad) console.error(`stale: ${f}`);
    if (bad.length) console.error("Run: node assets/branding/tokens/generate.mjs");
    else console.error("generated colour files are up to date");
    process.exit(bad.length ? 1 : 0);
  }
  rmSync(path.join(REPO, "assets/branding/generated/ios/LigusTokens.xcassets"), { recursive: true, force: true });
  for (const [rel, body] of Object.entries(render(tokens))) {
    const abs = path.join(REPO, rel);
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, body);
  }
  console.error(`wrote ${Object.keys(render(tokens)).length} files`);
}
